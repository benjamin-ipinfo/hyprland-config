#!/usr/bin/env python3
"""Generate ~/.config/hypr-platform/hypr/monitors.lua for PCs (not used on the Apple-silicon Macs).

For every connected monitor:
  mode     the panel's native resolution, at the highest refresh rate offered for it:
           the largest mode offered at >= 59 Hz, else Hyprland's "preferred" mode.
           Fake 4K input modes (3840x2160 / 4096x2160 on 1440p monitors) never win over
           the preferred mode.
  scale    from pixel density (physical size from EDID), so text is the same size everywhere:
           >= 190 ppi -> 2 (e.g. 27" 5K), >= 150 ppi -> 1.5 (e.g. 27" 4K), else 1 (e.g. 27" 1440p)
  vrr      2 (only while a fullscreen app runs) on monitors that can do >= 100 Hz
  position highest-resolution monitor at 0x0, the others to its right, top-aligned

Usage:
  monitors.py            print the generated config
  monitors.py --apply    write ~/.config/hypr-platform/hypr/monitors.lua and reload Hyprland
  monitors-setup         same as --apply (symlink in ~/.local/bin)
  monitors.py --json F   use a saved `hyprctl monitors all -j` dump instead (testing)
"""
import json
import os
import re
import subprocess
import sys
import time

OUT = os.path.expanduser("~/.config/hypr-platform/hypr/monitors.lua")


def query():
    out = subprocess.run(["hyprctl", "monitors", "all", "-j"],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def load_monitors():
    if "--json" in sys.argv:
        with open(sys.argv[sys.argv.index("--json") + 1]) as f:
            return json.load(f)
    # At first login a slow monitor (5K DSC link training) can appear a few seconds late:
    # wait until the monitor list has been stable for 3 s (max ~15 s).
    last, stable_since, deadline = None, time.time(), time.time() + 15
    while True:
        mons = query()
        names = sorted(m["name"] for m in mons)
        if names != last:
            last, stable_since = names, time.time()
        if (names and time.time() - stable_since >= 3) or time.time() > deadline:
            return mons
        time.sleep(1)


# Typical fake "input" modes of 1440p/1080p monitors (accepted, then downscaled).
FAKE_INPUT = {(3840, 2160), (4096, 2160)}


def best_mode(mon):
    rates = {}                                   # (w, h) -> highest refresh offered
    for m in mon.get("availableModes", []):
        r = re.match(r"(\d+)x(\d+)@([\d.]+)Hz", m)
        if r:
            size = (int(r[1]), int(r[2]))
            rates[size] = max(rates.get(size, 0), float(r[3]))
    # Start from the preferred mode (what Hyprland runs on first login). Some monitors
    # prefer a smaller mode than their panel, e.g. the ASUS XG27JCG 5K prefers
    # 3840x2160: take the largest mode that runs at >= 59 Hz, unless it's a fake 4K
    # input mode (those are often 30 Hz only, but some accept 60).
    w, h = mon["width"], mon["height"]
    full = [s for s, r in rates.items() if r >= 59]
    if full:
        big = max(full, key=lambda s: s[0] * s[1])
        if big[0] * big[1] > w * h and big not in FAKE_INPUT:
            w, h = big
    rate = rates.get((w, h), float(mon.get("refreshRate", 60)))
    return w, h, rate


def pick_scale(w, h, phys_w_mm):
    ppi = w / (phys_w_mm / 25.4) if phys_w_mm and phys_w_mm > 0 else None
    if ppi is None:  # no EDID size: guess from resolution
        return 2 if w >= 5120 else 1.5 if w >= 3840 else 1, None
    if ppi >= 190:
        return 2, ppi
    if ppi >= 150:
        return 1.5, ppi
    return 1, ppi


def fmt(x):
    return f"{x:g}"


def main():
    mons = [m for m in load_monitors() if not m.get("disabled")]
    plan = []
    for m in mons:
        w, h, rate = best_mode(m)
        scale, ppi = pick_scale(w, h, m.get("physicalWidth"))
        plan.append(dict(name=m["name"], desc=m.get("description", ""), w=w, h=h,
                         rate=rate, scale=scale, ppi=ppi))
    plan.sort(key=lambda p: (-(p["w"] * p["h"]), p["name"]))

    x = 0
    lines = ["-- Generated by amd64/hypr/scripts/monitors.py on first login.",
             "-- Edit freely, or regenerate with: monitors-setup   (not tracked in git)",
             ""]
    for p in plan:
        vrr = 2 if p["rate"] >= 100 else 0
        ppi = f"{p['ppi']:.0f} ppi" if p["ppi"] else "size unknown"
        lines.append(f"-- {p['desc']} ({ppi})")
        lines.append(
            f'hl.monitor({{ output = "{p["name"]}", mode = "{p["w"]}x{p["h"]}@{p["rate"]:.2f}", '
            f'position = "{x}x0", scale = {fmt(p["scale"])}, vrr = {vrr} }})')
        x += round(p["w"] / p["scale"])
    text = "\n".join(lines) + "\n"

    if not plan:
        print("No monitors found; not writing anything.", file=sys.stderr)
        sys.exit(1)
    if "--apply" in sys.argv or os.path.basename(sys.argv[0]) == "monitors-setup":
        if os.path.islink(OUT):   # e.g. -> monitors-workhorse.lua (tracked): don't overwrite it
            os.unlink(OUT)
        with open(OUT, "w") as f:
            f.write(text)
        subprocess.run(["hyprctl", "reload"], check=False, capture_output=True)
        subprocess.run(["notify-send", "-a", "monitors", "Monitors configured",
                        "\n".join(f'{p["name"]}: {p["w"]}x{p["h"]} @ {p["rate"]:.0f} Hz, scale {fmt(p["scale"])}'
                                  for p in plan)], check=False)
    print(text, end="")


if __name__ == "__main__":
    main()
